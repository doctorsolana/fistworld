/// A reusable logistics asset owned by an ordinary company. The first version
/// serves buyer-funded contracts; the price fields deliberately leave the
/// seam needed by later merchant speculation without creating another route
/// type.
#[derive(Component, Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
pub struct CompanyTradeRoute {
    pub company: CompanyId,
    pub warehouse: BuildingId,
    pub mode: TradeRouteMode,
    pub origin: SettlementId,
    pub destination: SettlementId,
    pub good: Good,
    pub cargo_target: u32,
    pub maximum_purchase_price: u64,
    pub minimum_destination_price: u64,
    pub automatic: bool,
    /// The appointed Company Master created and reviews this route through
    /// bounded commercial AI. Player-authored timetables and fixed civic
    /// contracts leave it false.
    #[serde(default)]
    pub autonomous_management: bool,
    /// Forecast retained for explanation and later comparison with realised
    /// results. It is not guaranteed income and may be negative after arrival.
    #[serde(default)]
    pub expected_trip_profit: i64,
    /// Confidence in the possibly stale market report used at founding.
    #[serde(default)]
    pub decision_confidence: u8,
    pub active_contract: Option<TradeContractId>,
    pub assigned_caravaner: Option<PersonId>,
    /// Index into `TradeRouteSchedule`; replicated for map/company UI only.
    pub current_stop: u8,
    pub status: TradeRouteStatus,
    pub completed_trips: u32,
    pub lifetime_units: u32,
    pub lifetime_delivery_revenue: u64,
    /// Company cash spent buying merchant cargo. Contract purchases remain
    /// buyer-funded and are retained only in trip audit fields.
    pub lifetime_purchase_cost: u64,
    /// Asking-value of merchant cargo physically consigned at route stops.
    /// This is not revenue until a real market buyer clears the listing.
    pub lifetime_consigned_value: u64,
}

#[derive(Serialize, Deserialize, Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct TradeRouteTrip {
    pub departed_day: u32,
    pub completed_day: u32,
    pub units: u32,
    /// Buyer-funded source purchase, retained for route audit rather than
    /// counted as an expense of the carrier company.
    pub source_purchase_cost: u64,
    pub source_market_fees: u64,
    pub delivery_revenue: u64,
    /// Merchant cargo offered to a destination market during this cycle.
    pub consigned_value: u64,
    pub stops_visited: u8,
    pub travel_world_seconds: u32,
}

pub const MAX_TRADE_ROUTE_TRIPS: usize = 32;

#[derive(Component, Serialize, Deserialize, Clone, Debug, Default, PartialEq, Eq)]
pub struct TradeRouteHistory {
    trips: Vec<TradeRouteTrip>,
}

impl TradeRouteHistory {
    pub fn trips(&self) -> &[TradeRouteTrip] {
        &self.trips
    }

    pub fn record(&mut self, trip: TradeRouteTrip) {
        if self.trips.len() == MAX_TRADE_ROUTE_TRIPS {
            self.trips.remove(0);
        }
        self.trips.push(trip);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn timetable_preserves_order_and_enforces_the_editor_bound() {
        let stops = vec![
            TradeRouteStop {
                settlement: SettlementId(1),
                action: TradeRouteStopAction::Buy,
            },
            TradeRouteStop {
                settlement: SettlementId(2),
                action: TradeRouteStopAction::Sell,
            },
            TradeRouteStop {
                settlement: SettlementId(3),
                action: TradeRouteStopAction::Unload,
            },
        ];
        let schedule = TradeRouteSchedule::new(stops.clone()).unwrap();
        assert_eq!(schedule.stops(), stops);
        assert!(TradeRouteSchedule::new(stops[..1].iter().copied()).is_none());
        assert!(
            TradeRouteSchedule::new((0..=MAX_TRADE_ROUTE_STOPS).map(|index| {
                TradeRouteStop {
                    settlement: SettlementId(index as u64),
                    action: TradeRouteStopAction::Buy,
                }
            }))
            .is_none()
        );
    }

    #[test]
    fn public_contract_schedule_is_locked_and_directional() {
        let schedule = TradeRouteSchedule::contract(SettlementId(7), SettlementId(9));
        assert_eq!(schedule.stops().len(), 2);
        assert_eq!(
            schedule.stops()[0],
            TradeRouteStop {
                settlement: SettlementId(7),
                action: TradeRouteStopAction::ContractPickup,
            }
        );
        assert_eq!(
            schedule.stops()[1],
            TradeRouteStop {
                settlement: SettlementId(9),
                action: TradeRouteStopAction::ContractDelivery,
            }
        );
    }
}
