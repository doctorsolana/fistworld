//! Durable inter-settlement trade contracts and company route assets.
//!
//! A route belongs to an ordinary company. There is intentionally no special
//! "trade company" category: a quarry concern, bakery or warehouse merchant
//! may all own the same asset and use the same accounting rules.

use bevy::prelude::*;
use serde::{Deserialize, Serialize};

use super::{BuildingId, CompanyId, PersonId, SettlementId, TradeContractId};
use crate::economy::{Good, MarketSeller};

pub const MAX_TRADE_ROUTE_STOPS: usize = 8;

/// Economic purpose of one durable company route. Contract carriers move
/// cargo already owned by a real buyer; merchant routes risk company cash and
/// use their ordered stop instructions.
#[derive(Serialize, Deserialize, Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum TradeRouteMode {
    #[default]
    ContractCarrier,
    Merchant,
}

impl TradeRouteMode {
    pub const fn label(self) -> &'static str {
        match self {
            Self::ContractCarrier => "Contract delivery",
            Self::Merchant => "Merchant trading",
        }
    }
}

/// One instruction in a repeating caravan timetable. A route carries one
/// good in the first implementation, while every stop independently decides
/// whether that good enters or leaves the wagon and whether coin changes
/// hands.
#[derive(Serialize, Deserialize, Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum TradeRouteStopAction {
    /// Load company-owned stock from a Storage Hall in this settlement.
    #[default]
    Load,
    /// Buy from this settlement's public exchange using company cash.
    Buy,
    /// Deposit into a company-owned Storage Hall without making a sale.
    Unload,
    /// Consign cargo to this settlement's public exchange at the route floor.
    Sell,
    /// Locked source instruction generated by a buyer-funded civic contract.
    ContractPickup,
    /// Locked destination instruction generated by a buyer-funded contract.
    ContractDelivery,
}

impl TradeRouteStopAction {
    pub const fn label(self) -> &'static str {
        match self {
            Self::Load => "Load owned stock",
            Self::Buy => "Buy at market",
            Self::Unload => "Unload to storage",
            Self::Sell => "Sell at market",
            Self::ContractPickup => "Collect contract cargo",
            Self::ContractDelivery => "Deliver contract cargo",
        }
    }

    pub const fn is_loading(self) -> bool {
        matches!(self, Self::Load | Self::Buy | Self::ContractPickup)
    }

    pub const fn is_unloading(self) -> bool {
        matches!(self, Self::Unload | Self::Sell | Self::ContractDelivery)
    }

    pub const fn is_locked_contract(self) -> bool {
        matches!(self, Self::ContractPickup | Self::ContractDelivery)
    }
}

#[derive(Serialize, Deserialize, Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct TradeRouteStop {
    pub settlement: SettlementId,
    pub action: TradeRouteStopAction,
}

/// Ordered, bounded timetable attached to a route asset. `Vec` keeps the
/// editor straightforward while the authoritative boundary enforces the
/// eight-stop cap; this component updates only when a master edits a route,
/// not every movement tick.
#[derive(Component, Serialize, Deserialize, Clone, Debug, Default, PartialEq, Eq)]
pub struct TradeRouteSchedule {
    stops: Vec<TradeRouteStop>,
}

impl TradeRouteSchedule {
    pub fn new(stops: impl IntoIterator<Item = TradeRouteStop>) -> Option<Self> {
        let stops: Vec<_> = stops.into_iter().collect();
        (stops.len() >= 2 && stops.len() <= MAX_TRADE_ROUTE_STOPS).then_some(Self { stops })
    }

    pub fn stops(&self) -> &[TradeRouteStop] {
        &self.stops
    }

    pub fn replace(&mut self, stops: impl IntoIterator<Item = TradeRouteStop>) -> bool {
        let stops: Vec<_> = stops.into_iter().collect();
        if stops.len() < 2 || stops.len() > MAX_TRADE_ROUTE_STOPS {
            return false;
        }
        self.stops = stops;
        true
    }

    pub fn contract(origin: SettlementId, destination: SettlementId) -> Self {
        Self {
            stops: vec![
                TradeRouteStop {
                    settlement: origin,
                    action: TradeRouteStopAction::ContractPickup,
                },
                TradeRouteStop {
                    settlement: destination,
                    action: TradeRouteStopAction::ContractDelivery,
                },
            ],
        }
    }
}

#[derive(Serialize, Deserialize, Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum TradeContractStatus {
    #[default]
    Open,
    Assigned,
    InTransit,
    Fulfilled,
    Cancelled,
}

impl TradeContractStatus {
    pub const fn label(self) -> &'static str {
        match self {
            Self::Open => "Awaiting carrier",
            Self::Assigned => "Carrier assigned",
            Self::InTransit => "Cargo in transit",
            Self::Fulfilled => "Fulfilled",
            Self::Cancelled => "Cancelled",
        }
    }

    pub const fn is_active(self) -> bool {
        matches!(self, Self::Open | Self::Assigned | Self::InTransit)
    }
}

/// A real civic buyer order backed by cash removed from the destination
/// treasury. Source sellers are paid at collection; unused escrow returns to
/// the destination when the contract closes.
#[derive(Component, Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
pub struct CivicTradeContract {
    /// Filled once a real seller has enough listed stock to accept the order.
    /// `None` is a public, cash-backed tender visible to potential suppliers.
    pub origin: Option<SettlementId>,
    pub destination: SettlementId,
    pub good: Good,
    pub source_seller: Option<MarketSeller>,
    pub requested_units: u32,
    pub delivered_units: u32,
    pub maximum_unit_price: u64,
    pub delivery_fee_per_bulk: u64,
    pub reserved_cash: u64,
    pub escrow_cash: u64,
    pub spent_on_goods: u64,
    pub spent_on_freight: u64,
    pub created_day: u32,
    pub last_attempt_day: u32,
    pub status: TradeContractStatus,
}

impl CivicTradeContract {
    pub const fn remaining_units(self) -> u32 {
        self.requested_units.saturating_sub(self.delivered_units)
    }
}

